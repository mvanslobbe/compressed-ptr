#!/usr/bin/env python3
"""Build single_include/cptr.hpp: every header in include/cptr in one file.

Usage: scripts/amalgamate.py [--check]

Headers are inlined in include order, each once; their own
`#include "cptr/..."` lines and `#pragma once` are dropped. mapped_cage.hpp
needs POSIX, so it is wrapped in `#if !defined(_WIN32)`. With --check, the
script fails if the committed file is out of date.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
INCLUDE = os.path.join(ROOT, "include")
OUT = os.path.join(ROOT, "single_include", "cptr.hpp")
TOP = ["all.hpp", "user_cage.hpp", "mapped_cage.hpp"]
INC = re.compile(r'^\s*#\s*include\s+"cptr/([\w.]+)"\s*$')

seen = set()
parts = []


def emit(name):
    if name in seen:
        return
    seen.add(name)
    body = []
    for line in open(os.path.join(INCLUDE, "cptr", name), encoding="utf-8"):
        m = INC.match(line)
        if m:
            emit(m.group(1))
            continue
        if line.strip() in ("#pragma once",) or line.startswith(
                "// SPDX-License-Identifier"):
            continue
        body.append(line)
    text = "".join(body).strip("\n")
    if name == "mapped_cage.hpp":
        text = "#if !defined(_WIN32)\n" + re.sub(
            r'#if defined\(_WIN32\)\n#\s*error[^\n]*\n#endif\n', "", text) + \
            "\n#endif  // !defined(_WIN32)"
    if name != "all.hpp":
        parts.append(f"// ---- cptr/{name} ----\n{text}\n")


for top in TOP:
    emit(top)

header = """// SPDX-License-Identifier: MIT
// compressed-ptr, single-header edition: 4-byte pointers and containers for
// 64-bit C++20. https://github.com/mvanslobbe/compressed-ptr
//
// Generated by scripts/amalgamate.py from include/cptr; do not edit.
// mapped_cage is only available on POSIX systems.
#pragma once

"""
result = header + "\n".join(parts)
if "--check" in sys.argv:
    current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if current != result:
        sys.exit("single_include/cptr.hpp is out of date; run "
                 "scripts/amalgamate.py")
    print("single_include/cptr.hpp is up to date")
else:
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(result)
    print(f"wrote {OUT}: {result.count(chr(10))} lines")
